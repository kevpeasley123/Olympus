//! Operator-authorized consent review using Olympus's existing connection code.
//! No credentials, exchange, refresh, revocation or generation are possible here.
use project_olympus_lib::commands::chatgpt_plan::{connection::{Connection,Provider},tokens::Store,Exchange};
use serde_json::Value;

struct ReviewOnly;
impl Store for ReviewOnly {
    fn load(&self,_:&str)->Result<Option<String>,String>{Err("Review mode cannot read credentials".into())}
    fn save(&self,_:&str,_:&str)->Result<(),String>{Err("Review mode cannot save credentials".into())}
    fn delete(&self,_:&str)->Result<(),String>{Err("Review mode cannot delete credentials".into())}
}
impl Provider for ReviewOnly {
    fn exchange(&self,_:&Exchange)->Result<(Value,Value),String>{Err("Consent returned; review mode stopped before token exchange. No credentials saved.".into())}
    fn revoke(&self,_:&str,_:&str)->Result<(),String>{Err("Review mode cannot revoke grants".into())}
}
fn main(){
    let mut args=std::env::args().skip(1);
    if args.next().as_deref()!=Some("--review-authorized") {eprintln!("Explicit operator authorization required");std::process::exit(2);}
    let Some(path)=args.next() else {eprintln!("Review metadata directory required");std::process::exit(2);};
    let connection=Connection::new(std::path::PathBuf::from(path),ReviewOnly);
    let result=connection.connect(None,&ReviewOnly,|url|{
        // Argument array, no shell interpolation; URL generated by Olympus only.
        std::process::Command::new("rundll32.exe").args(["url.dll,FileProtocolHandler",url]).spawn().map_err(|_|"System browser could not be opened")?;
        println!("Olympus consent review opened in the system browser. Do not approve until permissions have been reviewed. Token exchange and generation are disabled.");
        Ok(())
    },std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).expect("system clock").as_secs());
    if let Err(message)=result {eprintln!("{message}");}
}

#[cfg(test)]mod tests {
    use super::*;
    #[test]fn review_capabilities_cannot_touch_credentials_or_provider(){
        assert!(ReviewOnly.load("test").is_err());assert!(ReviewOnly.save("test","synthetic").is_err());assert!(ReviewOnly.delete("test").is_err());assert!(ReviewOnly.revoke("test","synthetic").is_err());
        let attempt=Exchange{client_id:"synthetic".into(),code:"synthetic".into(),verifier:"synthetic".into(),redirect:"http://127.0.0.1:1/auth/callback".into(),nonce:"synthetic".into()};
        assert!(ReviewOnly.exchange(&attempt).is_err());
    }
}
