const integrationBase=process.argv[2]??'http://127.0.0.1:31430';
import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1440,height:960}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(integrationBase+'/focused-map-harness.html');
 await page.getByRole('button',{name:'Focus branch: Inspections',exact:true}).click();
 assert.equal(await page.locator('.focused-branch').count(),8);
 for(let i=0;i<4;i++)await page.locator('.focused-pagination').getByRole('button',{name:'More',exact:true}).click();
 assert.equal(await page.locator('.focused-branch').count(),5);
 await page.getByRole('button',{name:'Refresh snapshot',exact:true}).click();
 assert.equal(await page.locator('.focused-branch').count(),5,'refresh retains page');
 await page.getByRole('button',{name:'Toggle mount',exact:true}).click();
 await page.getByRole('button',{name:'Toggle mount',exact:true}).click();
 assert.equal(await page.locator('.focused-branch').count(),5,'remount retains branch page');
 await page.getByRole('searchbox').fill('inspector@example.invalid');
 await page.locator('.focused-search-results').getByRole('button').first().click();
 assert.equal(await page.locator('.focused-detail-heading h2').textContent(),'Inspector 0');
 await page.getByRole('tab',{name:'Documents',exact:true}).click();
 await page.getByRole('button',{name:'Open document: A inspection report',exact:true}).waitFor();
 assert.equal(await page.locator('.focused-file').count(),1,'documents are scoped to selection');
 await page.getByRole('button',{name:'Open document: A inspection report',exact:true}).click();
 assert.equal(await page.locator('#opened').textContent(),'shared-id:report','native boundary receives IDs, not paths');
 await page.getByRole('tab',{name:'Conversations',exact:true}).click();
 await page.locator('.focused-thread').click();
 await page.getByText('Synthetic cached source.',{exact:false}).last().waitFor();
 assert.equal(await page.evaluate(()=>window.bad),undefined,'source HTML remains inert');
 assert.equal(await page.getByRole('button',{name:/Open document/}).count(),0,'attachment metadata does not enable opening');
 await page.getByRole('button',{name:'Switch account',exact:true}).click();
 assert.equal(await page.locator('.focused-detail-heading h2').textContent(),'Other account','new account does not inherit selection');
 await page.getByRole('tab',{name:'Documents',exact:true}).click();
 await page.getByText('File not currently available',{exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:/Open document/}).count(),0);
 assert.equal(await page.locator('.focused-detail').getByText('A inspection report',{exact:true}).count(),0);
 await page.getByRole('button',{name:'Switch account',exact:true}).click();
 assert.equal(await page.locator('.focused-detail-heading h2').textContent(),'Inspector 0','original account restores its own selection');
 await page.getByRole('button',{name:'Toggle empty',exact:true}).click();
 assert.equal(await page.locator('.focused-detail-heading h2').textContent(),'Home','removed selection safely falls back');
 await page.getByRole('tab',{name:'Documents',exact:true}).click();
 assert.ok(await page.getByText('No saved documents linked',{exact:true}).isVisible());
 await page.waitForTimeout(250);
 assert.equal(await page.getByRole('button',{name:/Open document/}).count(),0,'late source availability cannot revive removed files');
 assert.deepEqual(errors,[]);
 console.log('PASS large branches, retained page, remount, exact-contact search, document scoping/open IDs, inert sources, attachment honesty, account isolation, removed selection and late availability');
} finally {await browser.close()}
