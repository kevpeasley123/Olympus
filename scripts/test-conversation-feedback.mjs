import {build} from 'esbuild';
import assert from 'node:assert/strict';
await build({entryPoints:['src/services/conversationFeedback.ts'],bundle:true,platform:'node',format:'esm',outfile:'output/tests/conversation-feedback.mjs',logLevel:'warning'});
const {feedbackForBrief,requestConversationFeedback,resolveConversationTurn}=await import('../output/tests/conversation-feedback.mjs');
const source={accountId:'a',threadId:'t',signature:'sig',revision:0,subject:'Enrollment'};
const context=feedbackForBrief([{kind:'recommendation',emailSource:source},{kind:'progress'}]);
assert.deepEqual(context,{kind:'brief',itemCount:2,sources:[source]},'Mixed context preserves total highlight count for ambiguity checks');
assert.equal(feedbackForBrief([{kind:'context'}]),undefined);
const calls=[];const reply={content:'Recorded.',feedback:{...context,kind:'acknowledgment',itemCount:1}};
const client=async(command,args)=>{calls.push({command,args});return reply};
assert.equal(await requestConversationFeedback('chat','user',true,client),null);
assert.equal(await requestConversationFeedback(undefined,'user',false,client),null);
assert.equal(calls.length,0);
assert.deepEqual(await requestConversationFeedback('chat','user',false,client),reply);
assert.deepEqual(calls,[{command:'conversation_feedback',args:{conversationId:'chat',messageId:'user',temporary:false}}],'Only saved identities cross IPC; no composed source text or inferred correction');
await assert.rejects(requestConversationFeedback('chat','user',false,async()=>{throw Error('save failed')}),/save failed/);
let finishSave,modelCalls=0,localCalls=0;
const saved=new Promise(resolve=>{finishSave=resolve});
const model=async()=>{modelCalls++;return {content:'Model reply',model:'fixture',research:[]}};
const local=async()=>{localCalls++;return reply};
const pending=resolveConversationTurn(saved,{id:'chat',temporary:false},'user',model,local);
await Promise.resolve();
assert.equal(localCalls,0);assert.equal(modelCalls,0,'Nothing interprets the turn before its persistence completes');
finishSave(true);
assert.equal((await pending).content,'Recorded.');assert.equal(modelCalls,0,'A local correction does not invoke a model');
await assert.rejects(resolveConversationTurn(Promise.resolve(false),{id:'chat',temporary:false},'user',model,local),/could not be saved/);
assert.equal(localCalls,1);assert.equal(modelCalls,0);
assert.equal((await resolveConversationTurn(Promise.resolve(false),{id:'private',temporary:true},'user',model,local)).content,'Model reply');
assert.equal(localCalls,1);assert.equal(modelCalls,1);
assert.equal((await resolveConversationTurn(Promise.resolve(true),{id:'chat',temporary:false},'user',model,async()=>null)).content,'Model reply');
assert.equal(modelCalls,2,'Ordinary conversation retains its selected provider route');
await assert.rejects(resolveConversationTurn(Promise.resolve(true),{id:'chat',temporary:false,active:()=>false},'user',model,local),/Stopped/);
assert.equal(localCalls,1,'A stopped turn cannot apply a local correction after saving');
let active=true;
await assert.rejects(resolveConversationTurn(Promise.resolve(true),{id:'chat',temporary:false,active:()=>active},'user',model,async()=>{active=false;return null}),/Stopped/);
assert.equal(modelCalls,2,'A stop during local collection cannot launch a model afterward');
console.log('PASS brief source bindings, ambiguity count, private exclusion and local feedback IPC');
