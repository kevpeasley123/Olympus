import {build} from 'esbuild';
import {mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('output/tests',{recursive:true});
await build({entryPoints:['src/services/pantheonMissions.ts'],bundle:true,format:'esm',platform:'node',outfile:'output/tests/pantheon-missions.mjs'});
const {activeMissions,missionTelemetry,missionOrbit}=await import('../output/tests/pantheon-missions.mjs');
const make=(id,status,approval=null)=>({id,status,approval,steps:[]});
assert.deepEqual(activeMissions(null),[]);
assert.deepEqual(activeMissions({missions:[]}),[]);
assert.equal(activeMissions({missions:[make('a','running')]}).length,1);
const snapshot={missions:[make('a','running'),make('b','waiting'),...['completed','cancelled','failed','interrupted'].map(s=>make(s,s))]};
assert.deepEqual(activeMissions(snapshot).map(m=>m.id),['a','b']);
snapshot.missions[0].status='completed';assert.deepEqual(activeMissions(snapshot).map(m=>m.id),['b']);
assert.equal(activeMissions({missions:[make('a','running'),make('a','running')]}).length,1);
assert.equal(missionTelemetry(make('a','running')).progress,null);
assert.equal(missionTelemetry(make('a','waiting',{required:true})).state,'Awaiting approval');
assert.equal(missionTelemetry(make('a','waiting')).state,'Waiting');
assert.equal(missionTelemetry({...make('a','waiting'),steps:[{state:'failed'}]}).state,'Blocked');
const t=missionTelemetry({...make('a','running'),steps:[{state:'completed'},{state:'active'},{state:'pending'},{state:'skipped'},{state:'not-run'}]});
assert.equal(t.progress,1/3);assert.equal(t.progressLabel,'1/3 steps');
assert.deepEqual(missionOrbit('a'),missionOrbit('a'));assert.notDeepEqual(missionOrbit('a'),missionOrbit('b'));
assert(missionOrbit('a').period>=180 && missionOrbit('a').period<270);
console.log('PASS 15 mission lifecycle, telemetry and stable-orbit checks');
