import {build} from 'esbuild';
import {readFile,mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('output/tests',{recursive:true});
await build({entryPoints:['src/services/armoryPresentation.ts'],bundle:true,format:'esm',platform:'node',outfile:'output/tests/armory-presentation.mjs'});
const {armoryPlugins,pluginStatus,liveOperations}=await import('../output/tests/armory-presentation.mjs');
const fixture=JSON.parse(await readFile('src/services/capabilitiesFixture.json','utf8'));
const snapshot=fixture.capabilities;
assert.equal(armoryPlugins(null).length,0);
assert(armoryPlugins(snapshot).every(t=>!['model','executor'].includes(t.toolKind)));
assert(!armoryPlugins(snapshot).some(t=>['model-primary','claude-code'].includes(t.id)));
const gmail=snapshot.tools.find(t=>t.id==='gmail');
assert.equal(pluginStatus({...gmail,state:'UNAVAILABLE',detail:'Connected previously'}),'Unavailable');
assert.equal(pluginStatus({...gmail,state:'AVAILABLE',detail:'Configured'}),'Available');
assert.equal(pluginStatus({...gmail,state:'AVAILABLE',detail:'Connected / read only'}),'Connected');
assert.equal(pluginStatus({...gmail,id:'browser',state:'AVAILABLE',detail:'Connected'}),'Available');
assert.deepEqual(liveOperations(null),[]);
const statuses=['running','waiting','completed','failed','cancelled','interrupted'];
assert.deepEqual(liveOperations({missions:statuses.map(status=>({status}))}).map(m=>m.status),['running','waiting']);
console.log('PASS 9 Armory state and authorization distinction checks');
